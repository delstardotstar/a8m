"""Writes literal double-precision C models of the 70's eight networks,
straight from the listings in the description's data file (section 13.2:
signals, terms, stored, interp, start_at_unity, bypass, delay_ramp), with
the arithmetic of section 3 written out as stated (one 32 768-sample
buffer per stored signal, sgn(c) floor(|c| y), saturation after every
addition, the negative-start rule, taps returning 4w + 3), for
tools/r70test.c to check fw/src/r70.c against.

usage: python3 -I fw/tools/r70ref.py DATA.json OUT.c
"""
import json
import sys

data = json.load(open(sys.argv[1], encoding='utf-8'))
NETS = ['chorus', 'chords', 'multiband', 'multiband_b', 'chamber', 'inverse', 'plate', 'hall']
out = ['/* Generated by tools/r70ref.py from the 70\'s data file (section 5 listings). */',
       'static double rbuf[48][32768];',
       'static unsigned rt;',
       'static double rsat(double v) { return v > 131071 ? 131071 : v < -131072 ? -131072 : v; }',
       '/* sgn(c) floor(|c| y): c in units u of 1/res */',
       'static double rprod(double u, double res, double y) { double m = floor(fabs(u) / res * y); return u < 0 ? -m : m; }',
       'static double rstart(double u, double res, double y) { double m = floor(fabs(u) / res * y); return u < 0 ? -m - 1 : m; }',
       'static double rtap(int j, double d) { return 4 * rbuf[j][(rt - (unsigned)d) & 32767u] + 3; }',
       'static void rput(int j, double y) { rbuf[j][rt & 32767u] = floor(y / 4); }']

for ni, name in enumerate(NETS):
    n = data['networks'][name]
    coefs = list(n['coefficients'])
    res = {k: v['resolution'] for k, v in n['coefficients'].items()}
    delays = list(n['delays'])
    # The engine runs every coefficient in units of 1/256 (the snapshots'
    # values; 1/8 and 1/32 are exact in them). It gives every ramped product (7.3) its own coefficient, in
    # 1/32, and also the products that read a tap the bypass replaces.
    slots = {}
    for d, prods in n.get('delay_ramp', {}).get('products', {}).items():
        for p in prods:
            slots[(p['signal'], p['term'])] = (len(coefs) + len(slots), 256)
    froms = [r['from'] for r in n.get('bypass', {}).get('replace', [])]
    for sg in n['signals']:
        st = sg['start']
        ops = [('start', st['of'] if isinstance(st, dict) and 'of' in st else st)]
        ops += [(i, t['of']) for i, t in enumerate(sg['terms'])]
        for term, op in ops:
            if op in froms and (sg['name'], term) not in slots:
                slots[(sg['name'], term)] = (len(coefs) + len(slots), 256)
    stored = [s['name'] for s in n['signals'] if s.get('stored')]
    byp = [(r['from'], r['to']) for r in n.get('bypass', {}).get('replace', [])]

    def operand(op):
        if op == 'x':
            return 'x'
        if isinstance(op, str):
            return 'v_' + op
        for f, t in byp:
            if f == op:
                return '(byp ? %s : %s)' % (operand(t), tap(op))
        return tap(op)

    def tap(op):
        d = op['d']
        de = str(d) if isinstance(d, int) else 'dv[%d]' % delays.index(d)
        if op.get('add'):
            de = '(%s + %d)' % (de, op['add'])
        return 'rtap(%d, %s)' % (stored.index(op['tap']), de)

    def coef(c, key):
        if key in slots:
            i, r = slots[key]
            return 'cv[%d]' % i, str(r)
        neg = c.startswith('-')
        b = c[1:] if neg else c
        if b in res:
            return ('-' if neg else '') + 'cv[%d]' % coefs.index(b), '256'
        if '/' in b:
            num, den = b.split('/')
            return ('-' if neg else '') + num, den
        return ('-' if neg else '') + b, '1'

    out.append('static void ref_%s(const double *cv, const unsigned *dv, int byp, double x, double *L, double *R)' % name)
    out.append('{')
    out.append('    (void)byp;')
    for s in n['signals']:
        nm = s['name']
        st = s['start']
        if isinstance(st, dict) and 'of' in st:
            u, r = coef(st['c'], (nm, 'start'))
            e = 'rstart(%s, %s, %s)' % (u, r, operand(st['of']))
            if s.get('start_at_unity'):
                e = '(%s >= %s ? rsat(v_%s + rprod(%s - %s, %s, %s)) : %s)' % (
                    u, r, s['start_at_unity'], u, r, r, operand(st['of']), e)
            e = 'rsat(%s)' % e
        elif (nm, 'start') in slots:
            u, r = coef('1', (nm, 'start'))
            e = 'rsat(rstart(%s, %s, %s))' % (u, r, operand(st))
        else:
            e = operand(st)
        out.append('    double v_%s = %s;' % (nm, e))
        for ti, t in enumerate(s['terms']):
            u, r = coef(t['c'], (nm, ti))
            out.append('    v_%s = rsat(v_%s + rprod(%s, %s, %s));' % (nm, nm, u, r, operand(t['of'])))
        if s.get('interp'):
            ip = s['interp']
            u, r = coef(ip['k'], None)
            out.append('    if (%s == 256) v_%s = %s;' % (u, nm, operand(ip['B'])))
        if s.get('stored'):
            out.append('    rput(%d, v_%s);' % (stored.index(nm), nm))
    out.append('    *L = floor(v_%s / 4);' % n['outputs'][0])
    out.append('    *R = floor(v_%s / 4);' % n['outputs'][1])
    out.append('    rt++;')
    out.append('}')
out.append('static void (*const ref_net[8])(const double *, const unsigned *, int, double, double *, double *) = {')
out.append('    ' + ', '.join('ref_' + k for k in NETS))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
