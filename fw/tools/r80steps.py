"""Writes fw/src/r80_steps.h from fw/src/r80_tanks.h: each tank's memory
steps (ring << 8 | step) and fixed offsets (ring << 16 | offset), for
r80.c's per-block tap indices and prefetch.

usage: python3 -I fw/tools/r80steps.py [OUT]   (default fw/src/r80_steps.h;
       tools/r80test.sh checks the file is current)
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', 'src', 'r80_tanks.h')).read()
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'src', 'r80_steps.h')
lines = ['/* Generated by tools/r80steps.py from r80_tanks.h; do not edit. */']
for name in ['chamber', 'plate', 'hall', 'inverse']:
    body = re.search(r'static void TANK\(%s\)\(unsigned count\)\n\{(.*?)\n\}\n' % name, src, re.S).group(1)
    steps, fixed, ring_of = [], [], {}
    for kind, ring, n in re.findall(r'\b(RD|RDF|WR|WRF)\(m([012]),\s*([0-9]+)', body):
        ring, n = int(ring), int(n)
        if kind.endswith('F'):
            if (ring, n) not in fixed:
                fixed.append((ring, n))
            continue
        if ring_of.setdefault(n, ring) != ring:
            sys.exit('r80steps: step %d of %s in two rings' % (n, name))
        if (ring, n) not in steps:
            steps.append((ring, n))
    steps.sort()
    fixed.sort()
    lines.append('static const uint16_t steps_%s[] = { %s };' % (name, ', '.join('0x%03x' % (r << 8 | s) for r, s in steps)))
    lines.append('static const uint32_t fixed_%s[] = { %s };' % (name, ', '.join('0x%05x' % (r << 16 | o) for r, o in fixed)))
open(out, 'w').write('\n'.join(lines) + '\n')
