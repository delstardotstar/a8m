"""Writes literal double-precision C models of the 80's four tanks, straight
from the listings of section 5 of the spec (their read/write lists and
expanded expressions), for tools/r80test.c to check fw/src/r80.c against.

usage: python3 -I fw/tools/r80ref.py SPEC.md OUT.c
"""
import re
import sys

spec, out = sys.argv[1], sys.argv[2]
text = open(spec, encoding='utf-8').read()
TANKS = [('chamber', '## 5.1 Chamber tank', '## 5.2 Plate tank'),
         ('plate', '## 5.2 Plate tank', '## 5.3 Concert Hall tank'),
         ('hall', '## 5.3 Concert Hall tank', '## 5.4 Inverse tank'),
         ('inverse', '## 5.4 Inverse tank', '## 6. Modulation')]


def c_expr(e):
    e = e.replace('′', 'p')
    e = re.sub(r'X(\d+)p', r'xp[\1]', e)
    e = re.sub(r'X(\d+)', r'x[\1]', e)
    e = re.sub(r'k(\d+)', r'k[\1]', e)
    e = re.sub(r'(\d+)/(\d+)', r'\1.0/\2.0', e)
    e = re.sub(r'/(\d+)(?![.\d])', r'/\1.0', e)
    return e.replace('sendR', 'sr').replace('sendL', 'sl')


def off(o):
    return f'A[{o[1:]}]' if o.startswith('A') else o


lines = ['/* Generated by tools/r80ref.py from the spec\'s listings (5.1-5.4). */',
         'static double M[3][65536], x[127], xp[127];',
         'static unsigned n;',
         'static double clip(double v) { return v > 1 ? 1 : v < -1 ? -1 : v; }']
for name, start, end in TANKS:
    sec = text[text.index(start):text.index(end)]
    blocks = re.findall(r'```\n(.*?)```', sec, re.S)
    ops = re.findall(r'([RW])(\d+):(M\d)\[n-(A\d+|\d+)\]', blocks[0])
    exprs = {}
    for line in blocks[1].splitlines():
        m = re.match(r'(w(\d+)|retL|retR)\s*(?:\(M\d\))?\s*=\s*(.*)', line.strip())
        if m:
            exprs[m.group(2) or m.group(1)] = m.group(3)
    assert {s for k, s, _, _ in ops if k == 'W'} == set(exprs) - {'retL', 'retR'}, name
    lines += [f'static void ref_{name}(double sl, double sr, double *retL, double *retR, const double *k, '
              'const int *A)', '{']
    for kind, s, mem, o in ops:
        b = int(mem[1])
        if kind == 'R':
            lines.append(f'    x[{s}] = M[{b}][(n - {off(o)}) & 65535u];')
        else:
            lines.append(f'    M[{b}][(n - {off(o)}) & 65535u] = clip({c_expr(exprs[s])});')
    lines += [f'    *retL = clip({c_expr(exprs["retL"])});',
              f'    *retR = clip({c_expr(exprs["retR"])});',
              '    for (int i = 0; i < 127; i++) xp[i] = x[i];',
              '    n++;',
              '}']
open(out, 'w').write('\n'.join(lines) + '\n')
